-- SuryaPas: the seven tables of SPEC 4.1 and 4.3.
-- Stage 1 uses assessments, assumption_sets, sun_cache and events.
-- profiles, installers and quote_requests are created now and stay empty
-- until stages 2 and 3.
--
-- Written for plain Postgres 13 or later (gen_random_uuid is built in), so it
-- also runs on an empty Supabase database.

-- profiles: one row per signed-in user (stage 2). The id is a plain uuid for
-- now so this file needs no auth schema; stage 2 links it to auth.users.
create table profiles (
  id           uuid primary key default gen_random_uuid(),
  role         text not null check (role in ('homeowner', 'installer', 'admin')),
  display_name text,
  created_at   timestamptz not null default now()
);

-- assumption_sets: one version of the assumptions (SPEC 4.2). Rows are only
-- ever added; a changed number is a new version, never an edit.
create table assumption_sets (
  version    text primary key,
  created_at timestamptz not null default now(),
  entries    jsonb not null,
  note       text not null default ''
);

-- assessments: one saved calculation result.
-- id is generated by the server (src/lib/store/ids.ts): 128 random bits as
-- 22 URL-safe characters. It is the only thing that protects a result, so it
-- is never derived from a counter or from the inputs. The check below keeps
-- a hand-written insert from storing a guessable id.
-- assumption_set_version is deliberately not a foreign key: the result is
-- stored as shown, and the in-memory store used in development has no such
-- check either.
create table assessments (
  id                     text primary key check (id ~ '^[A-Za-z0-9_-]{22}$'),
  created_at             timestamptz not null default now(),
  locale                 text not null check (locale in ('id', 'en')),
  inputs                 jsonb not null,                      -- location, roof, electricity, lifestyle
  overrides              jsonb not null default '{}'::jsonb,  -- user-changed assumptions
  assumption_set_version text not null,
  engine_version         text not null,
  sun_source             text not null check (sun_source in ('live', 'fallback')),
  result                 jsonb not null,                      -- the engine output as it was shown
  owner_id               uuid references profiles (id)        -- null until stage 2
);

-- sun_cache: one 0.5 degree grid cell's hourly series for one year.
-- Nearby users share one NASA POWER fetch (SPEC 3.4).
create table sun_cache (
  cell_id    text not null,
  year       integer not null,
  fetched_at timestamptz not null default now(),
  series     jsonb not null,  -- 8,760 hourly values
  primary key (cell_id, year)
);

-- events: one anonymous count. No user, no IP, no device.
-- assessment_id is not a foreign key: it comes from the browser, and a stray
-- value must not make a count fail.
create table events (
  id            bigint generated always as identity primary key,
  created_at    timestamptz not null default now(),
  name          text not null,
  assessment_id text
);
create index events_name_created_at_idx on events (name, created_at);

-- installers: installer listings (stage 3).
create table installers (
  id            uuid primary key default gen_random_uuid(),
  profile_id    uuid references profiles (id),
  company_name  text not null,
  service_areas text[] not null default '{}',
  verified      boolean not null default false,
  created_at    timestamptz not null default now()
);

-- quote_requests: a homeowner asking an installer for a quote (stage 3).
-- The set of status values is decided in stage 3, so none is enforced yet.
create table quote_requests (
  id            uuid primary key default gen_random_uuid(),
  assessment_id text not null references assessments (id),
  installer_id  uuid not null references installers (id),
  status        text not null default 'requested',
  created_at    timestamptz not null default now()
);
